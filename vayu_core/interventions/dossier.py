class _WatermarkCanvas(canvas_mod.Canvas):
    """Stamps PROTOTYPE over the finished page.

    ReportLab's onPage hooks fire *before* the flowables are laid down, so a
    watermark drawn there ends up underneath every opaque table and image — it
    survived only in the whitespace at the bottom of the last page, which is
    exactly where nobody looks. Overriding showPage() puts it on top of the
    content, which is the whole point of a watermark on a document that must
    never be mistaken for a real enforcement order.
    """

    def showPage(self):
        self.saveState()
        self.setFont("Helvetica-Bold", 46)
        self.setFillColor(colors.Color(0.45, 0.50, 0.60, alpha=0.16))
        self.translate(A4[0] / 2, A4[1] / 2)
        self.rotate(38)
        self.drawCentredString(0, 0, "PROTOTYPE")
        self.restoreState()
        super().showPage()


def _watermark(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 7)
    canvas.setFillColor(MUTED)
    canvas.drawString(18 * mm, 10 * mm, WATERMARK)
    canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {doc.page}")
    canvas.setStrokeColor(LINE)
    canvas.line(18 * mm, 13 * mm, A4[0] - 18 * mm, 13 * mm)
    canvas.restoreState()


def _styles() -> dict:
    s = getSampleStyleSheet()
    return {
        "title": ParagraphStyle("t", parent=s["Title"], fontSize=17, leading=21,
                                textColor=INK, spaceAfter=2),
        "sub": ParagraphStyle("s", parent=s["Normal"], fontSize=8.5, textColor=MUTED),
        "h2": ParagraphStyle("h2", parent=s["Heading2"], fontSize=10.5, leading=13,
                             textColor=INK, spaceBefore=9, spaceAfter=4),
        "body": ParagraphStyle("b", parent=s["Normal"], fontSize=8.5, leading=11.5, textColor=INK),
        "small": ParagraphStyle("sm", parent=s["Normal"], fontSize=7.2, leading=9.5, textColor=MUTED),
        "cell": ParagraphStyle("c", parent=s["Normal"], fontSize=7.4, leading=9.2),
        "quote": ParagraphStyle("q", parent=s["Normal"], fontSize=8.2, leading=11,
                                leftIndent=8, textColor=INK),
        "warn": ParagraphStyle("w", parent=s["Normal"], fontSize=7.4, leading=9.6, textColor=WARN),
        "center": ParagraphStyle("ct", parent=s["Normal"], fontSize=7.5, alignment=TA_CENTER,
                                 textColor=MUTED),
    }


def _kv_table(rows: list[tuple[str, str]], st: dict, width: float) -> Table:
    data = [[Paragraph(f"<font color='#64748B'>{k}</font>", st["cell"]),
             Paragraph(v, st["cell"])] for k, v in rows]
    t = Table(data, colWidths=[width * 0.32, width * 0.68])
    t.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("LINEBELOW", (0, 0), (-1, -2), 0.4, LINE),
    ]))
    return t


