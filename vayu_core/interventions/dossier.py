def generate(
    candidate: Candidate,
    city: CityConfig,
    ward_geom: str | None,
    rec_lat: float,
    rec_lon: float,
    signal_ts: datetime | None = None,
    wind_dir_from_deg: float | None = None,
    forecast_note: str | None = None,
    out_dir: Path | None = None,
) -> Dossier:
    """Render the dossier for one candidate. Returns the saved path."""
    out_dir = out_dir or DOSSIER_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{candidate.id}.pdf"
    # Use the application clock, not the wall clock. In demo mode "now" is the
    # replayed instant, and mixing the two turned the PRD E2 signal->dossier
    # stopwatch into "368840m 7s" — 256 days — because the signal came from the
    # demo timeline and the generation stamp came from today.
    now = pd.Timestamp(get_settings().now())
    local = now.tz_convert(city.timezone)

    st = _styles()
    doc = SimpleDocTemplate(
        str(path), pagesize=A4,
        leftMargin=18 * mm, rightMargin=18 * mm, topMargin=15 * mm, bottomMargin=16 * mm,
        title=f"VAYU Intervention Order {candidate.id}",
        author="VAYU (prototype)",
        subject=f"{ACTION_LABEL.get(candidate.action_type, candidate.action_type)} — {candidate.ward_name}",
    )
    W = doc.width
    flow = []

    # --- header ---
    flow.append(Paragraph("VAYU · Intervention Order", st["title"]))
    flow.append(Paragraph(
        f"{candidate.id} &nbsp;·&nbsp; {city.name} &nbsp;·&nbsp; generated "
        f"{local.strftime('%d %b %Y, %H:%M')} {local.tzname()}", st["sub"]))
    flow.append(Spacer(1, 7))

    # candidate.title is already "<action label> — <target>"; prefixing the
    # action again produced "Stop work - construction site - Stop work -
    # construction site - Metro corridor extension".
    flow.append(Paragraph(f"<b>{candidate.title}</b>", st["h2"]))

    # --- the ask, up top: an inspector should not have to read to page 2 ---
    impact = [
        [f"Averted in {candidate.ward_name} (t+24h)", f"{candidate.ward_averted_ugm3:.2f} µg/m³"],
        ["Averted per person (mean)", f"{candidate.predicted_ugm3_averted:.2f} µg/m³"],
        ["People protected", f"{candidate.population_protected:,}"],
        ["Effort", f"{candidate.effort_units} team{'s' if candidate.effort_units > 1 else ''}"],
        ["Model confidence", f"{candidate.confidence:.2f}"],
        ["ROI score", f"{candidate.roi_score:,.1f}"],
    ]
    # Peak still belongs on the page, just not as a headline number.
    t = Table([[Paragraph(f"<font size=6.5 color='#64748B'>{k.upper()}</font><br/>"
                          f"<font size=11><b>{v}</b></font>", st["cell"]) for k, v in impact[:3]],
               [Paragraph(f"<font size=6.5 color='#64748B'>{k.upper()}</font><br/>"
                          f"<font size=11><b>{v}</b></font>", st["cell"]) for k, v in impact[3:]]],
              colWidths=[W / 3] * 3)
    t.setStyle(TableStyle([
        ("BOX", (0, 0), (-1, -1), 0.5, LINE),
        ("INNERGRID", (0, 0), (-1, -1), 0.4, LINE),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
    ]))
    flow.append(t)
    flow.append(Spacer(1, 4))
    flow.append(Paragraph(
        f"Predicted impact is a Gaussian plume counterfactual (source halted vs. source "
        f"running) under the forecast wind field, for <b>this site alone</b> — not for the "
        f"whole source category, whose ward-level share is given in the reasoning below. "
        f"<b>Averted per person</b> is the population-weighted mean across every ward the "
        f"plume reaches, which is what the ROI multiplies; the ward figure is what "
        f"{candidate.ward_name} itself gains. Both are 24-hour means and sit below the "
        f"modelled peak of {candidate.peak_ugm3_averted:.2f} µg/m³. Confidence combines "
        f"source-attribution confidence with the dispersion model's own (0.8 ceiling).",
        st["small"]))

    # --- where ---
    flow.append(Paragraph("1 · Target location", st["h2"]))
    dist = candidate.distance_km
    flow.append(_kv_table([
        ("Enforcement target", f"{candidate.source_lat:.5f}, {candidate.source_lon:.5f}"),
        ("Affected ward", f"{candidate.ward_name} ({candidate.ward_id})"),
        ("Distance to ward", f"{dist:.1f} km"),
        ("Directions", f'<link href="https://www.google.com/maps/search/?api=1&query='
                       f'{candidate.source_lat:.5f},{candidate.source_lon:.5f}" color="#0EA5E9">'
                       f"Open in Maps</link>"),
    ], st, W))
    flow.append(Spacer(1, 6))

    png = render_map(candidate, ward_geom, rec_lat, rec_lon, wind_dir_from_deg)
    img_buf = io.BytesIO(png)
    iw, ih = Image(io.BytesIO(png))._restrictSize(W, 78 * mm)
    flow.append(Image(img_buf, width=iw, height=ih))
    flow.append(Spacer(1, 8))

    # --- evidence ---
    flow.append(Paragraph("2 · Evidence", st["h2"]))
    if candidate.evidence:
        head = ["#", "Observation", "Location", "Distance", "Observed at", "Source"]
        rows = [[Paragraph(f"<b>{h}</b>", st["cell"]) for h in head]]
        for i, e in enumerate(candidate.evidence[:12], 1):
            ts = getattr(e, "timestamp", None)
            when = "—"
            if ts:
                try:
                    when = pd.Timestamp(ts).tz_convert(city.timezone).strftime("%d %b %H:%M")
                except (ValueError, TypeError):
                    when = str(ts)[:16]
            loc = f"{e.lat:.4f}, {e.lon:.4f}" if getattr(e, "lat", None) else "—"
            d = f"{e.distance_km:.1f} km" if getattr(e, "distance_km", None) is not None else "—"
            rows.append([
                Paragraph(str(i), st["cell"]),
                Paragraph(f"{e.label}<br/><font size=6 color='#64748B'>{e.detail or ''}</font>", st["cell"]),
                Paragraph(loc, st["cell"]),
                Paragraph(d, st["cell"]),
                Paragraph(when, st["cell"]),
                Paragraph(e.source or "—", st["cell"]),
            ])
        et = Table(rows, colWidths=[W * 0.04, W * 0.34, W * 0.16, W * 0.1, W * 0.15, W * 0.21],
                   repeatRows=1)
        et.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F1F5F9")),
            ("INNERGRID", (0, 0), (-1, -1), 0.35, LINE),
            ("BOX", (0, 0), (-1, -1), 0.5, LINE),
            ("TOPPADDING", (0, 0), (-1, -1), 3.5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3.5),
        ]))
        flow.append(et)
        if len(candidate.evidence) > 12:
            flow.append(Spacer(1, 3))
            flow.append(Paragraph(
                f"Showing 12 of {len(candidate.evidence)} evidence items, strongest first. "
                f"Full set retained in the audit log against this order ID.", st["small"]))
    else:
        flow.append(Paragraph("No discrete evidence items attached.", st["small"]))

    flow.append(Spacer(1, 4))
    flow.append(Paragraph(f"<b>Attribution reasoning.</b> {candidate.rationale}", st["body"]))

    # --- law ---
    flow.append(Paragraph("3 · Regulatory basis", st["h2"]))
    reg = candidate.regulation
    if reg:
        block = [
            Paragraph(f"<b>{reg['title']}</b>", st["body"]),
            Spacer(1, 2),
            Paragraph(f"<i>{reg['instrument']} — {reg['clause']}</i>", st["small"]),
            Spacer(1, 4),
            Paragraph(f'"{reg["text"]}"', st["quote"]),
            Spacer(1, 4),
            Paragraph(f"<b>Citation:</b> {reg['citation']}", st["small"]),
        ]
        if reg.get("penalty_reference"):
            block.append(Paragraph(f"<b>Penalty:</b> {reg['penalty_reference']}", st["small"]))
        block.append(Spacer(1, 3))
        block.append(Paragraph(
            "Abridged restatement for a prototype. Verify against the current CAQM order "
            "at caqm.nic.in before issuing.", st["warn"]))
        bt = Table([[block]], colWidths=[W])
        bt.setStyle(TableStyle([
            ("BOX", (0, 0), (-1, -1), 0.5, LINE),
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#FEFCE8")),
            ("LEFTPADDING", (0, 0), (-1, -1), 9),
            ("RIGHTPADDING", (0, 0), (-1, -1), 9),
            ("TOPPADDING", (0, 0), (-1, -1), 7),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
        ]))
        flow.append(KeepTogether(bt))
    else:
        flow.append(Paragraph(
            "<b>No regulatory clause matched.</b> This order cannot be issued until a legal "
            "basis is identified.", st["warn"]))

    # --- provenance & sign-off ---
    flow.append(Paragraph("4 · Provenance", st["h2"]))
    prov = [
        ("Signal detected", signal_ts.astimezone(local.tzinfo).strftime("%d %b %Y, %H:%M")
         if signal_ts else "—"),
        ("Dossier generated", local.strftime("%d %b %Y, %H:%M")),
    ]
    if signal_ts is not None:
        elapsed = (now - pd.Timestamp(signal_ts)).total_seconds()
        prov.append(("Signal → dossier", f"{int(elapsed // 60)}m {int(elapsed % 60)}s"))
    prov += [
        ("Attribution", "Evidence fusion — NASA FIRMS VIIRS, OpenAQ/CPCB, Open-Meteo winds, "
                        "OSM road network"),
        ("Dispersion", "Gaussian plume, Briggs (1973) rural coefficients, Pasquill-Gifford "
                       "stability from wind &amp; boundary-layer height"),
        ("Emission factors", "Wooster et al. (2005) FRP→fuel; Andreae &amp; Merlet (2001) PM2.5"),
    ]
    if forecast_note:
        prov.append(("Forecast context", forecast_note))
    flow.append(_kv_table(prov, st, W))

    flow.append(Paragraph("5 · Authorisation", st["h2"]))
    flow.append(Paragraph(
        "VAYU recommends; a human authorises. This order is not valid until signed below.",
        st["small"]))
    flow.append(Spacer(1, 10))
    sign = [
        ["Recommended by", "Authorised by", "Executed by"],
        ["VAYU (automated)\nconfidence %.2f" % candidate.confidence, "", ""],
        ["", "", ""],
    ]
    sd = [[Paragraph(f"<font size=6.5 color='#64748B'>{c.upper()}</font>", st["cell"]) for c in sign[0]],
          [Paragraph(sign[1][0].replace("\n", "<br/>"), st["cell"]),
           Paragraph("<br/><br/>Name / Designation", st["small"]),
           Paragraph("<br/><br/>Name / Designation", st["small"])],
          [Paragraph("<br/>Date &amp; time", st["small"]),
           Paragraph("<br/>Signature &amp; date", st["small"]),
           Paragraph("<br/>Signature &amp; date", st["small"])]]
    t = Table(sd, colWidths=[W / 3] * 3, rowHeights=[14, 34, 30])
    t.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOX", (0, 0), (-1, -1), 0.5, LINE),
        ("INNERGRID", (0, 0), (-1, -1), 0.4, LINE),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
    ]))
    flow.append(t)

    flow.append(Spacer(1, 9))
    dt = Table([[Paragraph(DISCLAIMER, st["small"])]], colWidths=[W])
    dt.setStyle(TableStyle([
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#FCA5A5")),
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#FEF2F2")),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    flow.append(dt)

    doc.build(flow, onFirstPage=_watermark, onLaterPages=_watermark,
              canvasmaker=_WatermarkCanvas)
    logger.info(f"dossier {candidate.id} -> {path} ({path.stat().st_size / 1024:.0f} KB)")
    return Dossier(order_id=candidate.id, path=path, generated_ts=now)
