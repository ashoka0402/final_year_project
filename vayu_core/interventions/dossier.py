"""Evidence dossier PDF — VAYU's unit of output (PRD C2).

Everything upstream converges here. The forecast, the back-trajectory, the fire
detections, the plume counterfactual and the GRAP clause all exist so that this
one page can be handed to an inspector who was not in the room. It must stand on
its own: where to go, what was seen, under what authority, what it should
achieve, and who signed it.

Renderer choice — a documented deviation from TRD 5.6, which prefers WeasyPrint
with a reportlab fallback. WeasyPrint needs native glib/Pango/Cairo, which are
absent on a clean macOS without Homebrew and raise OSError at import. A dossier
that cannot render is a demo with no product, so the sanctioned fallback is the
primary path here. reportlab is pure Python and imports clean.

The map is a schematic locator drawn from ward geometry, not satellite imagery —
labelled as such on the page so nobody mistakes it for a basemap. It carries what
an inspector needs (source pin, ward, wind vector, scale) and needs no network at
dispatch time.
"""

