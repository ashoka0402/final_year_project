def _ward_polygon(geom_geojson: str | None) -> list[np.ndarray]:
    """Exterior rings from a GeoJSON Polygon/MultiPolygon string."""
    if not geom_geojson:
        return []
    try:
        g = json.loads(geom_geojson)
    except (json.JSONDecodeError, TypeError):
        return []
    t = g.get("type")
    if t == "Polygon":
        polys = [g["coordinates"]]
    elif t == "MultiPolygon":
        polys = g["coordinates"]
    else:
        return []
    return [np.asarray(p[0], dtype=float) for p in polys if p and p[0]]


def render_map(
    candidate: Candidate,
    ward_geom: str | None,
    rec_lat: float,
    rec_lon: float,
    wind_dir_from_deg: float | None = None,
) -> bytes:
    """Schematic locator: source, affected ward, wind vector, scale bar.

    Drawn offline from ward geometry so a dispatch never blocks on a tile
    server. Deliberately labelled a schematic — it is not imagery.
    """
    fig, ax = plt.subplots(figsize=(7.0, 4.2), dpi=150)

    lats = [candidate.source_lat, rec_lat]
    lons = [candidate.source_lon, rec_lon]

    for ring in _ward_polygon(ward_geom):
        ax.fill(ring[:, 0], ring[:, 1], facecolor="#BAE6FD", edgecolor="#0369A1",
                linewidth=1.2, alpha=0.45, zorder=1)
        lons += list(ring[:, 0])
        lats += list(ring[:, 1])

    # Evidence pixels — the raw detections behind the claim.
    ev_pts = [(e.lon, e.lat) for e in candidate.evidence if getattr(e, "lat", None)]
    if ev_pts:
        ex, ey = zip(*ev_pts)
        ev_label = ("Satellite detections"
                    if all(e.type == "fire" for e in candidate.evidence if getattr(e, "lat", None))
                    else "Evidence")
        ax.scatter(ex, ey, s=26, c="#F97316", marker="s", edgecolors="#7C2D12",
                   linewidths=0.5, zorder=4, label=ev_label)
        lons += list(ex)
        lats += list(ey)

    # Padding: never let a tight cluster zoom to absurd scale.
    pad = max(0.04, (max(lats) - min(lats)) * 0.25, (max(lons) - min(lons)) * 0.25)
    x0, x1 = min(lons) - pad, max(lons) + pad
    y0, y1 = min(lats) - pad, max(lats) + pad

    ax.plot([candidate.source_lon, rec_lon], [candidate.source_lat, rec_lat],
            ls="--", lw=1.2, color=MUTED.hexval().replace("0x", "#")[:7], zorder=2)

    ax.scatter([rec_lon], [rec_lat], s=150, c="#0EA5E9", marker="o",
               edgecolors="white", linewidths=1.5, zorder=5, label="Affected ward")
    ax.scatter([candidate.source_lon], [candidate.source_lat], s=230, c="#DC2626",
               marker="*", edgecolors="white", linewidths=1.0, zorder=6, label="Enforcement target")

    # Wind vector: points the way the air travels (from -> to).
    if wind_dir_from_deg is not None and np.isfinite(wind_dir_from_deg):
        to_deg = (float(wind_dir_from_deg) + 180.0) % 360.0
        theta = np.deg2rad(to_deg)
        dx, dy = np.sin(theta), np.cos(theta)
        L = (x1 - x0) * 0.13
        ax.arrow(x0 + (x1 - x0) * 0.09, y1 - (y1 - y0) * 0.13, dx * L, dy * L,
                 head_width=L * 0.32, head_length=L * 0.32, fc="#334155", ec="#334155", zorder=7)
        ax.text(x0 + (x1 - x0) * 0.09, y1 - (y1 - y0) * 0.06,
                f"wind {int(wind_dir_from_deg)}°", fontsize=7, color="#334155")

    # Scale bar — an inspector needs to read distance off the page.
    km_per_deg_lon = haversine_km(rec_lat, rec_lon, rec_lat, rec_lon + 1.0)
    if km_per_deg_lon > 0:
        target_km = max(5.0, round((x1 - x0) * km_per_deg_lon / 4 / 5) * 5)
        bar = target_km / km_per_deg_lon
        bx, by = x0 + (x1 - x0) * 0.06, y0 + (y1 - y0) * 0.08
        ax.plot([bx, bx + bar], [by, by], lw=2.5, color=INK.hexval().replace("0x", "#")[:7])
        ax.text(bx + bar / 2, by + (y1 - y0) * 0.02, f"{target_km:.0f} km",
                fontsize=7, ha="center", color="#0F172A")

    ax.set_xlim(x0, x1)
    ax.set_ylim(y0, y1)
    # Keep degrees square-ish at this latitude so distances aren't visually skewed.
    ax.set_aspect(1.0 / np.cos(np.deg2rad(rec_lat)))
    ax.set_xticks([])
    ax.set_yticks([])
    for s in ax.spines.values():
        s.set_color("#CBD5E1")
    ax.legend(loc="lower right", fontsize=6.5, framealpha=0.9)
    ax.set_title("Schematic locator — not to-scale imagery", fontsize=7, color="#64748B", loc="left")

    buf = io.BytesIO()
    fig.tight_layout(pad=0.4)
    fig.savefig(buf, format="png", bbox_inches="tight")
    plt.close(fig)
    return buf.getvalue()


