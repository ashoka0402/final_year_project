# This prototype must never be mistaken for a real enforcement order. The
# watermark is on every page, and the disclaimer block is not optional.
WATERMARK = "PROTOTYPE — not an official document"
DISCLAIMER = (
    "This document was generated by VAYU, a prototype decision-support system. "
    "It is <b>not an official order</b> and carries no legal "
    "force. Regulation text is an abridged restatement for demonstration and must be "
    "verified against the current CAQM order before any enforcement action. Predicted "
    "impact comes from a Gaussian plume model with stated confidence, not a measurement."
)

